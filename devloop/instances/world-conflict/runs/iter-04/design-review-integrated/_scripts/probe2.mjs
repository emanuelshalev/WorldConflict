// Probe the rest of month 1: answer a call, leave one open, recommended, All orders, Map, review, execute, result, paper.
import { browser, openTitle, shot, facts, text, buttons, mkLog } from './lib.mjs';
const log = mkLog('log-probe2.txt');
const b = await browser();
const { page } = await openTitle(b);
const btn = (re) => page.getByRole('button', { name: re }).first();
const tryClick = async (re, t = 3000) => btn(re).click({ timeout: t }).then(() => true, (e) => { log('MISS', String(re), e.message.split('\n')[0]); return false; });
const dump = async (tag, n = 2500) => { await shot(page, `p-${tag}`); log(`--- ${tag} text`, (await text(page)).slice(0, n)); log(`${tag} buttons`, await buttons(page)); log(`${tag} facts`, await facts(page)); };
await tryClick(/^Take office/);
await page.waitForTimeout(2500);
await tryClick(/^Take office/);
await page.waitForTimeout(2500);
await tryClick(/Reply via Muscat/);
await page.waitForTimeout(1200);
await dump('10-after-answer');
await tryClick(/^Next/);
await page.waitForTimeout(1200);
await dump('11-mission-move');
await page.getByRole('button', { name: /^Recommended orders/ }).first().click().catch((e) => log('MISS rec', e.message.split('\n')[0]));
await page.waitForTimeout(1200);
await dump('12-recommended');
await tryClick(/^Choose all recommended/);
await page.waitForTimeout(1200);
await dump('13-after-choose-all');
await tryClick(/^All orders/);
await page.waitForTimeout(1500);
await dump('14-all-orders');
log('errors', page.errors);
await b.close();
