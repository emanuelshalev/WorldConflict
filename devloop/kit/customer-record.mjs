#!/usr/bin/env node
// Build the customer record: everything every customer has said, in every round, linked to the
// project state it was said about (method/customer-advocate.md). Generated, never hand-edited;
// the Customer Advocate reads it instead of opening dozens of session files.
//
//   node devloop/kit/customer-record.mjs <instanceDir> [--check]
//
// Reads  <instance>/runs/iter-NN/sessions/*.json (method/report.schema.json),
//        <instance>/runs/iter-NN/findings.json or patterns.json (triage clusters),
//        <instance>/panel/panel.yaml (weights). Published states are named by their tag <tagPrefix>N.
// Writes <instance>/customer-record/record.json   everything, machine readable
//        <instance>/customer-record/INDEX.md      project states and where each round's material is
//        <instance>/customer-record/liked.md      every positive statement, by round (input of the keep list)
//        <instance>/customer-record/<persona>.md  one customer's history, newest round first
// --check writes nothing and exits 1 when the files on disk differ from what would be generated.
// Output is deterministic (no timestamps), so an unchanged record gives an empty diff.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { iterations, panelWeights, runDirOf, sessionsOf } from './feedback-digest.mjs';

const GENERATED = 'Generated by devloop/kit/customer-record.mjs. Do not edit: change the session reports or the triage files and regenerate.';
const pad = (n) => String(n).padStart(2, '0');
const one = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();
const rel = (instanceDir, file) => path.relative(path.join(instanceDir, 'customer-record'), file).split(path.sep).join('/');

function readJsonFile(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    return null;
  }
}

/** Triage clusters of one iteration, normalised: { id, title, severity, weight, personas, decision, status, tone }. */
export function clustersOf(instanceDir, iter) {
  const dir = runDirOf(instanceDir, iter);
  const findings = readJsonFile(path.join(dir, 'findings.json'));
  const list = Array.isArray(findings) ? findings : (findings?.findings ?? findings?.clusters);
  if (Array.isArray(list)) {
    return list.map((f) => ({
      id: f.id,
      title: one(f.title),
      severity: f.severity ?? null,
      weight: f.weight ?? null,
      personas: f.personas ?? f.who ?? [],
      decision: f.decision ?? null,
      status: f.status ?? null,
      tone: f.tone ?? 'bad',
    }));
  }
  const patterns = readJsonFile(path.join(dir, 'patterns.json'));
  return (patterns?.patterns ?? []).map((f) => ({
    id: f.id,
    title: one(f.title),
    severity: f.severity ?? null,
    weight: f.weight ?? null,
    personas: f.who ?? f.personas ?? [],
    decision: f.decision ?? null,
    status: f.status ?? null,
    tone: f.tone ?? 'bad',
  }));
}

/** What the round's triage recorded as loved (patterns.json `loved`), as plain strings. */
function lovedOf(instanceDir, iter) {
  const patterns = readJsonFile(path.join(runDirOf(instanceDir, iter), 'patterns.json'));
  return (patterns?.loved ?? []).map((l) => (typeof l === 'string' ? one(l) : one(l.title ?? l.what ?? JSON.stringify(l))));
}

/** Positive statements of one session: the structured `liked` rows first, then the older `delight` strings. */
export function positivesOf(session) {
  const rows = [];
  for (const l of session.liked ?? []) {
    rows.push({
      what: one(l.what),
      where: one(l.where),
      why: one(l.why),
      strength: l.strength ?? null,
      would_miss: l.would_miss ?? null,
    });
  }
  for (const d of session.delight ?? []) rows.push({ what: one(d), where: '', why: '', strength: null, would_miss: null });
  return rows;
}

/** A score is { value, reason } in the report schema; older reports may hold a bare number. */
const scoreValue = (v) => (typeof v === 'number' ? v : typeof v?.value === 'number' ? v.value : null);

export function buildRecord(instanceDir, { tagPrefix = 'iter-' } = {}) {
  const weights = panelWeights(instanceDir);
  const states = [];
  const personas = {};
  for (const iter of iterations(instanceDir)) {
    const dir = runDirOf(instanceDir, iter);
    const sessions = sessionsOf(instanceDir, iter).filter((s) => s?.persona);
    if (!sessions.length) continue;
    const clusters = clustersOf(instanceDir, iter);
    const builds = [...new Set(sessions.map((s) => s.build).filter(Boolean))].sort();
    const scored = sessions.filter((s) => scoreValue(s.scores?.recommend) != null);
    const wsum = scored.reduce((a, s) => a + (weights[s.persona] ?? 0), 0);
    const recommend = wsum ? scored.reduce((a, s) => a + scoreValue(s.scores.recommend) * (weights[s.persona] ?? 0), 0) / wsum : null;
    const exists = (f) => (fs.existsSync(path.join(dir, f)) ? rel(instanceDir, path.join(dir, f)) : null);
    states.push({
      iteration: iter,
      tag: `${tagPrefix}${iter}`,
      builds_played: builds,
      sessions: sessions.length,
      weighted_recommend: recommend == null ? null : Math.round(recommend * 100) / 100,
      end_reached: sessions.some((s) => s.tasks) ? sessions.filter((s) => s.tasks?.end_reached).length : null,
      brief: exists('CUSTOMER_BRIEF.md'),
      triage: exists('triage.md'),
      clusters: exists('findings.json') ?? exists('patterns.json'),
      forecast: exists('advocate-forecast.md'),
      forecast_review: exists('advocate-review.md'),
      loved: lovedOf(instanceDir, iter),
    });
    for (const s of sessions.sort((a, b) => a.persona.localeCompare(b.persona))) {
      const p = (personas[s.persona] ??= { weight: weights[s.persona] ?? null, rounds: [] });
      p.rounds.push({
        iteration: iter,
        variant: s.variant,
        device: s.device ?? null,
        build: s.build,
        minutes_played: s.minutes_played ?? null,
        scores: Object.fromEntries(Object.entries(s.scores ?? {}).map(([k, v]) => [k, scoreValue(v)])),
        score_reasons: Object.fromEntries(Object.entries(s.scores ?? {}).filter(([, v]) => v?.reason).map(([k, v]) => [k, one(v.reason)])),
        end_reached: s.tasks?.end_reached ?? null,
        outcomes: (s.scenarios ?? []).map((x) => `${x.id}: ${x.outcome}, ${x.turns} turns`),
        quit_point: s.quit_point ?? null,
        verbatim: one(s.verbatim),
        would_miss_most: one(s.would_miss_most) || null,
        pull_to_continue: one(s.pull_to_continue) || null,
        liked: positivesOf(s),
        friction: (s.friction ?? []).map((f) => ({ kind: f.kind, where: one(f.where), happened: one(f.happened) })),
        bugs: (s.bugs ?? []).map((b) => ({ severity: b.severity, title: one(b.title) })),
        suggestions: (s.suggestions ?? []).map((x) => one(x.what)),
        clusters: clusters.filter((c) => c.personas.includes(s.persona)).map((c) => ({ id: c.id, title: c.title, severity: c.severity, decision: c.decision, status: c.status, tone: c.tone })),
        source: rel(instanceDir, path.join(dir, 'sessions', `${s.variant}.json`)),
      });
    }
  }
  return { note: GENERATED, states, personas };
}

const fmt = (v) => (v == null ? 'n/a' : String(v));

function indexMd(record) {
  const out = ['# Customer record: project states', '', GENERATED, ''];
  out.push('One row per customer round. "Tag" is the git tag the iteration is published under (`git show <tag>` gives the published commit; an iteration that was never published has no such tag); "Played" is the build the customers actually played, which is earlier than the tag when fixes followed the round.', '');
  out.push('| Iteration | Tag | Played | Sessions | Weighted recommend | Reached an end | Brief | Triage | Clusters | Forecast | Forecast review |');
  out.push('|---|---|---|---|---|---|---|---|---|---|---|');
  const link = (f, t) => (f ? `[${t}](${f})` : 'none');
  for (const s of record.states) {
    out.push(`| ${s.iteration} | ${s.tag} | ${s.builds_played.join(', ') || 'n/a'} | ${s.sessions} | ${fmt(s.weighted_recommend)} | ${s.end_reached == null ? 'not recorded' : `${s.end_reached} of ${s.sessions}`} | ${link(s.brief, 'brief')} | ${link(s.triage, 'triage')} | ${link(s.clusters, 'clusters')} | ${link(s.forecast, 'forecast')} | ${link(s.forecast_review, 'review')} |`);
  }
  out.push('', '## Customers', '', '| Customer | Weight | Rounds | Recommend by round |', '|---|---|---|---|');
  for (const [id, p] of Object.entries(record.personas)) {
    out.push(`| [${id}](${id}.md) | ${fmt(p.weight)} | ${p.rounds.length} | ${p.rounds.map((r) => `it${r.iteration}: ${fmt(r.scores.recommend)}`).join(', ')} |`);
  }
  out.push('', 'Every positive statement by round: [liked.md](liked.md). Everything, machine readable: [record.json](record.json).', '');
  return out.join('\n');
}

function likedMd(record) {
  const out = ['# What customers liked, by round', '', GENERATED, '', 'Raw input of the keep list (`keep-list.md`, written by the Customer Advocate). "Would miss" is the customer\'s own answer where the brief asked for it.', ''];
  for (const s of [...record.states].reverse()) {
    out.push(`## Iteration ${s.iteration} (played ${s.builds_played.join(', ') || 'n/a'})`, '');
    if (s.loved.length) out.push('Triage summary of what was loved:', ...s.loved.map((l) => `- ${l}`), '');
    for (const [id, p] of Object.entries(record.personas)) {
      const r = p.rounds.find((x) => x.iteration === s.iteration);
      if (!r) continue;
      const rows = r.liked;
      if (!rows.length && !r.would_miss_most && !r.pull_to_continue) continue;
      out.push(`### ${id} (${r.variant}, recommend ${fmt(r.scores.recommend)})`);
      if (r.would_miss_most) out.push(`- Would miss most: ${r.would_miss_most}`);
      if (r.pull_to_continue) out.push(`- Wanted to go on because: ${r.pull_to_continue}`);
      for (const l of rows) {
        const extra = [l.where && `where: ${l.where}`, l.why && `why: ${l.why}`, l.strength != null && `strength ${l.strength}`, l.would_miss != null && `would miss: ${l.would_miss ? 'yes' : 'no'}`].filter(Boolean).join('; ');
        out.push(`- ${l.what}${extra ? ` (${extra})` : ''}`);
      }
      out.push('');
    }
  }
  return out.join('\n');
}

function personaMd(id, p) {
  const out = [`# ${id}: customer history`, '', GENERATED, '', `Panel weight ${fmt(p.weight)}. Newest round first.`, ''];
  const keys = ['recommend', 'fun', 'clarity', 'visual', 'feels_like_a_game', 'agency', 'realism', 'replay'];
  out.push(`| Iteration | Variant | Build | ${keys.join(' | ')} | End reached |`, `|---|---|---|${keys.map(() => '---').join('|')}|---|`);
  for (const r of [...p.rounds].reverse()) out.push(`| ${r.iteration} | ${r.variant} | ${r.build} | ${keys.map((k) => fmt(r.scores[k])).join(' | ')} | ${r.end_reached == null ? 'n/a' : r.end_reached ? 'yes' : 'no'} |`);
  out.push('');
  for (const r of [...p.rounds].reverse()) {
    out.push(`## Iteration ${r.iteration} (${r.variant}, build ${r.build})`, '', `Source: [${r.source.split('/').pop()}](${r.source})${r.outcomes.length ? `. Played: ${r.outcomes.join('; ')}` : ''}.`, '');
    if (r.verbatim) out.push(`In their words: ${r.verbatim}`, '');
    if (r.score_reasons.recommend) out.push(`Why that recommend score: ${r.score_reasons.recommend}`, '');
    if (r.quit_point) out.push(`Would have quit: ${one(r.quit_point)}`, '');
    if (r.would_miss_most) out.push(`Would miss most: ${r.would_miss_most}`, '');
    if (r.pull_to_continue) out.push(`Wanted to go on because: ${r.pull_to_continue}`, '');
    if (r.liked.length) out.push('Liked:', ...r.liked.map((l) => `- ${l.what}${l.why ? ` (why: ${l.why})` : ''}`), '');
    if (r.friction.length) out.push('Friction:', ...r.friction.map((f) => `- [${f.kind}] ${f.where}: ${f.happened}`), '');
    if (r.bugs.length) out.push('Bugs reported:', ...r.bugs.map((b) => `- ${b.severity}: ${b.title}`), '');
    if (r.suggestions.length) out.push('Asked for:', ...r.suggestions.map((x) => `- ${x}`), '');
    if (r.clusters.length) out.push('Triage clusters this customer is part of:', ...r.clusters.map((c) => `- ${c.id} ${c.title}${c.severity ? ` (${c.severity})` : ''}${c.decision ? `, decision: ${c.decision}` : ''}`), '');
  }
  return out.join('\n');
}

/** { relative file: content } of everything the record consists of. */
export function renderRecord(record) {
  const files = { 'record.json': `${JSON.stringify(record, null, 1)}\n`, 'INDEX.md': indexMd(record), 'liked.md': likedMd(record) };
  for (const [id, p] of Object.entries(record.personas)) files[`${id}.md`] = personaMd(id, p);
  return files;
}

export function writeRecord(instanceDir, { check = false, tagPrefix } = {}) {
  const dir = path.join(instanceDir, 'customer-record');
  const files = renderRecord(buildRecord(instanceDir, { tagPrefix }));
  const stale = [];
  for (const [name, text] of Object.entries(files)) {
    const file = path.join(dir, name);
    const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
    if (old === text) continue;
    stale.push(name);
    if (!check) {
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(file, text);
    }
  }
  return { dir, files: Object.keys(files), stale };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const instanceDir = args.find((a) => !a.startsWith('--'));
  if (!instanceDir) {
    console.error('usage: customer-record.mjs <instanceDir> [--check]');
    process.exit(2);
  }
  const r = writeRecord(path.resolve(instanceDir), { check });
  if (check && r.stale.length) {
    console.error(`customer record is stale: ${r.stale.join(', ')}. Run: node devloop/kit/customer-record.mjs ${instanceDir}`);
    process.exit(1);
  }
  console.log(check ? `customer record up to date (${r.files.length} files)` : `customer record: ${r.files.length} files in ${path.relative(process.cwd(), r.dir)}, ${r.stale.length} changed`);
}
